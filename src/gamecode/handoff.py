"""handoff.py — serialize agent context to .md files for cross-agent hand-off."""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional


@dataclass
class TranscriptEntry:
    role: str   # "user" | "agent" | "guardrail" | "system"
    text: str

    _ROLE_DISPLAY = {
        "user": "🧑 User",
        "agent": "🤖 Agent",
        "guardrail": "🛡️ Guardrail",
        "system": "⚙️ System",
    }

    def to_markdown(self) -> str:
        label = self._ROLE_DISPLAY.get(self.role, self.role.title())
        return f"### {label}\n\n{self.text}\n"


@dataclass
class HandoffContext:
    session_id: str
    from_agent: str
    from_agent_name: str
    to_agent: str
    to_agent_name: str
    transcript: list[TranscriptEntry] = field(default_factory=list)
    open_tasks: list[str] = field(default_factory=list)
    summary: str = ""
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


class HandoffManager:
    """
    Writes .md hand-off files under:
        <base_dir>/<session_id>/<NNN>_<from>_to_<to>.md
    """

    def __init__(self, base_dir: Path | str):
        self.base_dir = Path(base_dir)
        self.base_dir.mkdir(parents=True, exist_ok=True)

    def _session_dir(self, session_id: str) -> Path:
        d = self.base_dir / session_id
        d.mkdir(parents=True, exist_ok=True)
        return d

    def write(self, ctx: HandoffContext) -> Path:
        session_dir = self._session_dir(ctx.session_id)
        seq = len(list(session_dir.glob("*.md"))) + 1
        path = session_dir / f"{seq:03d}_{ctx.from_agent}_to_{ctx.to_agent}.md"

        lines = [
            f"# Context Hand-off: {ctx.from_agent_name} → {ctx.to_agent_name}",
            "",
            f"- **Session ID:** `{ctx.session_id}`",
            f"- **Timestamp:** `{ctx.created_at.isoformat()}`",
            f"- **From Agent:** `{ctx.from_agent}` ({ctx.from_agent_name})",
            f"- **To Agent:** `{ctx.to_agent}` ({ctx.to_agent_name})",
            "",
            "---",
            "",
            "## Summary",
            "",
            (ctx.summary.strip() or "_No summary provided._"),
            "",
            "## Conversation Transcript",
            "",
        ]
        if ctx.transcript:
            lines.extend(entry.to_markdown() for entry in ctx.transcript)
        else:
            lines.append("_No messages were exchanged before the hand-off._")
            lines.append("")

        lines.extend(["## Open Tasks / Next Steps", ""])
        if ctx.open_tasks:
            lines.extend(f"- [ ] {task}" for task in ctx.open_tasks)
        else:
            lines.append("- [ ] _(none specified — proceed from summary)_")
        lines.extend([
            "",
            "---",
            "",
            f"*Generated by GameCode at {ctx.created_at.isoformat()}. "
            "The incoming agent should read this file and continue "
            "the task without asking the user to repeat context.*",
            "",
        ])

        path.write_text("\n".join(lines), encoding="utf-8")
        return path

    def read(self, path: Path | str) -> str:
        p = Path(path)
        return p.read_text(encoding="utf-8") if p.exists() else ""

    def list_for_session(self, session_id: str) -> list[Path]:
        d = self.base_dir / session_id
        return sorted(d.glob("*.md")) if d.exists() else []

    def read_latest(self, session_id: str) -> Optional[str]:
        files = self.list_for_session(session_id)
        return self.read(files[-1]) if files else None